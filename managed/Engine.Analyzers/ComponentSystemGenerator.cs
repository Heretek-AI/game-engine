// ComponentSystemGenerator.cs — M2-02 / ABI 4.2: IComponent.Tick -> native chunk job.
//
// An IIncrementalGenerator that intercepts every `partial struct : IComponent`
// carrying a `Tick(...)` method and emits a sibling partial with:
//   * an [UnmanagedCallersOnly] static `RunChunk(EngineChunkColumns*, float dt)`
//     that wraps each term column in a Span/ReadOnlySpan and invokes the
//     user's Tick per row, catching any exception (see `Faulted`), and
//   * `Register(ApiTable*, EngineWorld*, void*)`, which registers every
//     component type of the Tick by name (Engine.Runtime.Ecs.ComponentId<T>)
//     and binds RunChunk through system_register (ABI 4.2).
//
// Calling convention (matches the M2-01 Tick contract `Tick(ref Self self,
// ...)`): instance Tick is driven through the column element itself —
// `col0[i].Tick(ref col0[i], ...)` — where the element is BOTH the receiver
// AND the explicit ref/in self argument. This is NOT redundant: an instance
// method's hidden `this` and an explicit `ref Self` parameter are different
// slots, and omitting the explicit argument is CS7036. Component k of the
// Tick is native term k (`ref` = read-write, `in` = read-only); every
// `float` parameter receives the frame delta dt.
//
// Pipeline (value-equatable throughout; no symbol/syntax held past its stage):
//   syntax: every partial struct declaring a method named Tick.
//   model: resolve IComponent conformance + Tick overloads to SystemSpec.
//   emit: one .g.cs per system struct.
//
// Frame-path rules for EMITTED code: no managed allocations, no throws
// across the ABI (UCO methods must not throw), thread-safe statics only.
using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.IO;
using System.Linq;
using System.Threading;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Engine.Analyzers;

/// <summary>
/// Generates zero-copy native chunk runners for <c>IComponent</c> systems.
/// Matches <c>partial struct : IComponent</c> declarations with a user
/// <c>Tick</c> method and emits the UCO entry point plus registration.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class ComponentSystemGenerator : IIncrementalGenerator
{
    private const string IComponentMetadataName = "Engine.Runtime.IComponent";

    /// <inheritdoc/>
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        // Stage 0: emit the ABI-guard sentinel ONCE (not per system — a
        // per-file duplicate would be CS0101 with 2+ systems, and a file-level
        // type ahead of a file-scoped namespace would be CS8956).
        context.RegisterPostInitializationOutput(static pi => pi.AddSource(
            "EngineRequireExtraColumns.g.cs",
            "// <auto-generated/>\n// Engine.Analyzers (M2-02): ABI-guard sentinel.\n#nullable enable\nnamespace Engine.Generated;\ninternal static class EngineRequireExtraColumns\n{\n    internal static void Unsupported() => throw new System.NotSupportedException(\"Tick shape exceeds the EcsChunkView ABI (M2-04).\");\n}\n"));
        // Stage 1 (syntax only, cheap): every partial struct declaring a
        // method literally named Tick. No semantic work here so unchanged
        // files stay cached.
        var structs = context.SyntaxProvider
            .CreateSyntaxProvider(
                predicate: static (node, _) => IsSystemCandidate(node),
                transform: static (ctx, ct) => ToStructRef(ctx, ct))
            .Where(static r => r is not null);

        // Stage 2 (symbols, cached per struct): resolve IComponent + Ticks.
        var systems = context.CompilationProvider
            .Combine(structs.Collect())
            .SelectMany(static (pair, ct) => ResolveAll(pair.Left, pair.Right, ct));

        context.RegisterSourceOutput(systems, static (spc, spec) => EmitOne(spc, spec));
    }

    // --- Stage 1: syntax ---------------------------------------------------

    private static bool IsSystemCandidate(SyntaxNode node)
    {
        // Partial struct with a member literally named Tick. Interface
        // conformance, arity, and modifiers resolve in stage 2 against
        // symbols (syntax cannot see IComponent).
        if (node is not StructDeclarationSyntax s)
        {
            return false;
        }

        if (!s.Modifiers.Any(SyntaxKind.PartialKeyword))
        {
            return false;
        }

        foreach (var member in s.Members)
        {
            if (member is MethodDeclarationSyntax m && m.Identifier.ValueText == "Tick")
            {
                return true;
            }
        }

        return false;
    }

    private static string? ToStructRef(GeneratorSyntaxContext ctx, CancellationToken ct)
    {
        // Freeze the fully-qualified metadata name as the cross-stage key.
        // The compilation in stage 2 resolves it back to a symbol; nothing
        // here holds syntax or symbols past this transform.
        if (ctx.SemanticModel.GetDeclaredSymbol(ctx.Node, ct) is not INamedTypeSymbol sym)
        {
            return null;
        }

        return sym.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
    }

    private static bool IsPartial(INamedTypeSymbol sym, CancellationToken ct)
    {
        // Partial-ness is a SYNTAX property: every declaration must carry the
        // partial modifier. Check the declaring references, not the symbol
        // (symbols merge partial parts and lose the modifier info).
        foreach (var decl in sym.DeclaringSyntaxReferences)
        {
            ct.ThrowIfCancellationRequested();
            if (decl.GetSyntax(ct) is not TypeDeclarationSyntax tds ||
                !tds.Modifiers.Any(SyntaxKind.PartialKeyword))
            {
                return false;
            }
        }

        return sym.DeclaringSyntaxReferences.Length != 0;
    }

    // --- Stage 2: symbols --------------------------------------------------

    private static ImmutableArray<SystemSpec> ResolveAll(
        Compilation compilation,
        ImmutableArray<string?> refs,
        CancellationToken ct)
    {
        var iComponent = compilation.GetTypeByMetadataName(IComponentMetadataName);
        if (iComponent is null)
        {
            return ImmutableArray<SystemSpec>.Empty;
        }

        var builder = ImmutableArray.CreateBuilder<SystemSpec>();
        var seen = new HashSet<string>();
        foreach (var name in refs)
        {
            ct.ThrowIfCancellationRequested();
            if (name is null || !seen.Add(name))
            {
                continue;
            }

            var spec = ResolveOne(compilation, iComponent, name, ct);
            if (spec is not null)
            {
                builder.Add(spec);
            }
        }

        return builder.ToImmutable();
    }

    private static SystemSpec? ResolveOne(
        Compilation compilation,
        INamedTypeSymbol iComponent,
        string fullyQualifiedName,
        CancellationToken ct)
    {
        var sym = ResolveByName(compilation, fullyQualifiedName);
        if (sym is null)
        {
            return null;
        }

        if (!Implements(sym, iComponent))
        {
            return null;
        }

        // The generator emits a sibling `public partial struct`
        // redeclaration: the system struct itself must be public (a
        // narrower re-declaration is CS0262) and partial (guaranteed by
        // the stage-1 predicate) and non-generic (open generics have no
        // concrete sizeof/chunk layout; the M2-04 loader only binds
        // closed ones).
        if (sym.IsGenericType || !IsPartial(sym, ct)
            || sym.DeclaredAccessibility != Accessibility.Public)
        {
            return null;
        }

        // Every outer must also be partial: the emitter re-opens each
        // containing type, and re-opening a non-partial outer is CS0260.
        for (var c = sym.ContainingType; c is not null; c = c.ContainingType)
        {
            if (!IsPartial(c, ct))
            {
                return null;
            }
        }

        var ticks = ImmutableArray.CreateBuilder<TickSignatureSnapshot>();
        foreach (var method in sym.GetMembers("Tick").OfType<IMethodSymbol>())
        {
            ct.ThrowIfCancellationRequested();
            if (method.IsStatic || method.DeclaredAccessibility != Accessibility.Public)
            {
                continue;
            }

            // Generic Tick overloads need explicit type arguments at the call
            // site; a chunk runner cannot supply them. `out` params cannot be
            // satisfied from a column element either. Both are skipped (a
            // struct with no emittable overload produces no runner).
            if (method.IsGenericMethod || method.Parameters.Any(static p => p.RefKind == RefKind.Out))
            {
                continue;
            }

            var pars = ImmutableArray.CreateBuilder<TickParameterSnapshot>();
            foreach (var p in method.Parameters)
            {
                TickRefKind kind;
                if (p.RefKind == RefKind.Ref)
                {
                    kind = TickRefKind.Ref;
                }
                else if (p.RefKind == RefKind.In)
                {
                    kind = TickRefKind.In;
                }
                else
                {
                    kind = TickRefKind.None;
                }
                pars.Add(new TickParameterSnapshot(
                    kind,
                    p.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat),
                    p.Name));
            }

            ticks.Add(new TickSignatureSnapshot(
                pars.ToImmutable(),
                ReadPhases(method),
                SelfRefKind(pars)));
        }

        if (ticks.Count == 0)
        {
            return null;
        }

        var containing = ImmutableArray.CreateBuilder<ContainingTypeSnapshot>();
        for (var c = sym.ContainingType; c is not null; c = c.ContainingType)
        {
            containing.Add(SnapshotContaining(c));
        }

        return new SystemSpec(
            sym.ContainingNamespace.IsGlobalNamespace
                ? string.Empty
                : sym.ContainingNamespace.ToDisplayString(),
            sym.Name,
            containing.ToImmutable(),
            ticks.ToImmutable(),
            ReadPhases(sym));
    }

    private static TickRefKind SelfRefKind(ImmutableArray<TickParameterSnapshot>.Builder pars)
    {
        // The column element doubles as receiver AND self arg: its ref-ness
        // comes from the first ref/in COMPONENT param. float scalars (e.g. an
        // `in float dt` leading the signature) are skipped — they receive the
        // frame delta at the call site and never select the column kind.
        // TickRefKind.None when the Tick takes scalars only (unrunnable).
        foreach (var p in pars)
        {
            if (IsFloatScalar(p.TypeName))
            {
                continue;
            }

            if (p.RefKind == TickRefKind.Ref || p.RefKind == TickRefKind.In)
            {
                return p.RefKind;
            }
        }

        return TickRefKind.None;
    }

    private static ContainingTypeSnapshot SnapshotContaining(INamedTypeSymbol c)
    {
        // Re-open each outer with its own keyword + type args, omitting
        // accessibility (legal in partial redeclarations, avoids CS0262 when
        // the user nests under private/internal scopes). Generic outers keep
        // their parameter names so member references still resolve.
        var keyword = c.IsRecord
            ? (c.IsValueType ? "record struct" : "record class")
            : (c.IsValueType ? "struct" : "class");
        var typeArgs = c.IsGenericType
            ? "<" + string.Join(", ", c.TypeParameters.Select(static tp => tp.Name)) + ">"
            : string.Empty;
        return new ContainingTypeSnapshot(keyword, c.Name, typeArgs);
    }

    private static INamedTypeSymbol? ResolveByName(Compilation compilation, string fullyQualifiedName)
    {
        // FullyQualifiedFormat renders "global::A.B.C<D, E>"; walk the
        // namespace/type chain with the symbol API instead of re-parsing.
        var stripped = fullyQualifiedName.StartsWith("global::", System.StringComparison.Ordinal)
            ? fullyQualifiedName.Substring("global::".Length)
            : fullyQualifiedName;

        INamespaceOrTypeSymbol scope = compilation.GlobalNamespace;
        foreach (var part in SplitDotted(stripped))
        {
            var next = scope.GetMembers(part).OfType<INamespaceOrTypeSymbol>().FirstOrDefault();
            if (next is null)
            {
                return null;
            }

            scope = next;
        }

        return scope as INamedTypeSymbol;
    }

    private static IEnumerable<string> SplitDotted(string dotted)
    {
        // Nested types render "Outer.Inner": GetMembers resolves each level.
        // Generic arity suffixes ("List`1") are left intact — GetMembers
        // understands them for metadata lookup.
        var depth = 0;
        var current = new StringBuilder();
        foreach (var ch in dotted)
        {
            if (ch == '<')
            {
                depth++;
            }
            else if (ch == '>')
            {
                depth--;
            }

            if (ch == '.' && depth == 0)
            {
                yield return current.ToString();
                current.Clear();
            }
            else
            {
                current.Append(ch);
            }
        }

        yield return current.ToString();
    }

    private static bool Implements(INamedTypeSymbol sym, INamedTypeSymbol iComponent)
    {
        foreach (var iface in sym.AllInterfaces)
        {
            if (SymbolEqualityComparer.Default.Equals(iface, iComponent))
            {
                return true;
            }
        }

        return false;
    }

    private static ImmutableArray<string> ReadPhases(ISymbol sym)
    {
        var builder = ImmutableArray.CreateBuilder<string>();
        foreach (var attr in sym.GetAttributes())
        {
            var cls = attr.AttributeClass;
            // Match by NAME, not namespace: the attribute resolves through
            // `using Engine.Runtime;` in user code, and ToDisplayString
            // renders it relative to that context (bare
            // "UpdateInPhaseAttribute"). M2-01 declares exactly one such
            // attribute; matching the short name is the robust check.
            if (cls is null || cls.Name != "UpdateInPhaseAttribute")
            {
                continue;
            }

            if (attr.ConstructorArguments.Length == 1)
            {
                var v = attr.ConstructorArguments[0];
                builder.Add(PhaseName(v));
            }
        }

        return builder.ToImmutable();
    }

    private static string PhaseName(TypedConstant v)
    {
        // Enum-typed phase args surface as their underlying int (TypedConstant
        // boxes Phase.Render as 4); map back through the M2-01 Phase order so
        // the runner comment and the M2-04 loader agree on the phase token.
        if (v.Kind == TypedConstantKind.Enum && v.Value is int n)
        {
            return n switch
            {
                0 => "Startup",
                1 => "PreUpdate",
                3 => "PostUpdate",
                4 => "Render",
                _ => "Update",
            };
        }

        return v.Value?.ToString() ?? "Update";
    }

    // --- Stage 3: emit -----------------------------------------------------

    private static void EmitOne(SourceProductionContext spc, SystemSpec spec)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("// Engine.Analyzers (ABI 4.2): IComponent chunk runner.");
        sb.AppendLine("// Matches NativeApi.EngineChunkColumns; no allocation, Tick exceptions are caught.");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("using System;");
        sb.AppendLine("using System.Runtime.CompilerServices;");
        sb.AppendLine("using System.Runtime.InteropServices;");
        sb.AppendLine("using Engine.Bindings;");
        sb.AppendLine();
        if (spec.Namespace.Length != 0)
        {
            sb.AppendLine($"namespace {spec.Namespace};");
            sb.AppendLine();
        }

        // Only public system structs reach here (ResolveOne rejects the
        // rest); the redeclaration keeps the declared accessibility.
        OpenContaining(sb, spec);
        sb.AppendLine($"    public partial struct {spec.StructName}");
        sb.AppendLine("    {");

        var tick = spec.Ticks[0];
        // Canonical self identity (one construction site): both IsRunnable
        // and the emitters compare against this selfFqn form.
        var outerPath = string.Join(".", spec.ContainingTypes.Reverse().Select(static c => c.Name + c.TypeArgs));
        var selfFqn = (spec.Namespace.Length == 0 ? "global::" : "global::" + spec.Namespace + ".")
            + (spec.ContainingTypes.Length == 0 ? string.Empty : outerPath + ".")
            + spec.StructName;
        // First runnable overload wins: a scalars-only first overload would
        // otherwise emit the -2 guard even when a later overload maps onto
        // the ABI. Deterministic (declaration order), never empty — Ticks[0]
        // is the fallback when none is runnable.
        foreach (var candidate in spec.Ticks)
        {
            if (IsRunnable(candidate, selfFqn))
            {
                tick = candidate;
                break;
            }
        }
        EmitSizeRegistration(sb, spec, tick, selfFqn);
        EmitChunkRunner(sb, spec, tick, selfFqn);

        sb.AppendLine("    }");
        CloseContaining(sb, spec);

        var hint = "Chunk_" + spec.Namespace.Replace(".", "_") + "_" +
            string.Join("_", spec.ContainingTypes.Reverse().Select(static c => c.Name)) +
            (spec.ContainingTypes.Length == 0 ? string.Empty : "_") +
            spec.StructName + ".g.cs";
        // File-scoped namespace + file-local lookup: "Chunk__Mover.g.cs".
        // Legal hint names avoid characters identifier rules reject.
        foreach (var ch in Path.GetInvalidFileNameChars())
        {
            hint = hint.Replace(ch, '_');
        }

        spc.AddSource(hint.TrimStart('_'), sb.ToString());
    }

    private static void OpenContaining(StringBuilder sb, SystemSpec spec)
    {
        // Re-open each outer with ITS OWN kind + type args, omitting
        // accessibility (legal in partial redeclarations, avoids CS0262).
        // Non-partial outers never reach here: ResolveOne rejects them.
        foreach (var outer in spec.ContainingTypes.Reverse())
        {
            sb.AppendLine($"    partial {outer.Keyword} {outer.Name}{outer.TypeArgs}");
            sb.AppendLine("    {");
        }
    }

    private static void CloseContaining(StringBuilder sb, SystemSpec spec)
    {
        for (var i = 0; i < spec.ContainingTypes.Length; i++)
        {
            sb.AppendLine("    }");
        }
    }

    // ABI 4.2 contract for a RUNNABLE Tick (see IsRunnable):
    //   * every component parameter is `ref` (read-write term) or `in`
    //     (read-only term) and names a distinct type;
    //   * the FIRST component parameter is the system struct itself (its
    //     column element is both the receiver and the explicit self arg);
    //   * at most NativeApi.MaxTerms (8) component parameters;
    //   * every other parameter is a `float` (by value or `in`) and receives
    //     the frame delta dt passed to systems_run.
    // Anything else (by-value structs, double, out, >8 components, a
    // duplicate component type) is unrunnable: Register returns -2 without
    // touching native code and no Tick call is emitted.
    private const int MaxTerms = 8;

    private static void EmitSizeRegistration(StringBuilder sb, SystemSpec spec, TickSignatureSnapshot tick, string selfFqn)
    {
        sb.AppendLine("        /// <summary>");
        sb.AppendLine("        /// Byte size of this component (Flecs registration).");
        sb.AppendLine("        /// </summary>");
        sb.AppendLine($"        public static unsafe int ComponentSize => unchecked((int)sizeof({spec.StructName}));");
        sb.AppendLine();
        sb.AppendLine("        private static int s_faulted;");
        sb.AppendLine();
        sb.AppendLine("        /// <summary>");
        sb.AppendLine("        /// True after Tick threw once. The runner then skips every later");
        sb.AppendLine("        /// chunk (fault isolation: the exception never crosses the ABI).");
        sb.AppendLine("        /// </summary>");
        sb.AppendLine("        public static bool Faulted => global::System.Threading.Volatile.Read(ref s_faulted) != 0;");
        sb.AppendLine();
        if (!IsRunnable(tick, selfFqn))
        {
            sb.AppendLine("        /// <summary>");
            sb.AppendLine("        /// Registration is unavailable: this Tick shape cannot map onto");
            sb.AppendLine("        /// EngineChunkColumns. Returns -2 without calling into native code.");
            sb.AppendLine("        /// </summary>");
            sb.AppendLine("        public static unsafe int Register(NativeApi.ApiTable* table, NativeApi.EngineWorld* world, void* userData)");
            sb.AppendLine("        {");
            sb.AppendLine("            _ = table;");
            sb.AppendLine("            _ = world;");
            sb.AppendLine("            _ = userData;");
            sb.AppendLine("            return -2;");
            sb.AppendLine("        }");
            sb.AppendLine();
            return;
        }

        var components = ComponentParams(tick);
        var systemName = SystemName(spec);
        sb.AppendLine("        /// <summary>");
        sb.AppendLine("        /// Registers every component of this Tick with the native world and");
        sb.AppendLine("        /// binds RunChunk as a generic system. Returns the native system");
        sb.AppendLine("        /// index (>= 0), -1 for a null table/world, or a negative");
        sb.AppendLine("        /// NativeApi.Err* code from system_register.");
        sb.AppendLine("        /// </summary>");
        sb.AppendLine("        public static unsafe int Register(NativeApi.ApiTable* table, NativeApi.EngineWorld* world, void* userData)");
        sb.AppendLine("        {");
        sb.AppendLine("            if (table == null || world == null)");
        sb.AppendLine("            {");
        sb.AppendLine("                return -1;");
        sb.AppendLine("            }");
        sb.AppendLine();
        sb.AppendLine($"            ulong* ids = stackalloc ulong[{components.Count}];");
        sb.AppendLine($"            uint* access = stackalloc uint[{components.Count}];");
        for (var k = 0; k < components.Count; k++)
        {
            var p = components[k];
            sb.AppendLine($"            ids[{k}] = global::Engine.Runtime.Ecs.ComponentId<{p.TypeName}>(table, world);");
            sb.AppendLine($"            access[{k}] = {(p.RefKind == TickRefKind.In ? "NativeApi.AccessIn" : "NativeApi.AccessInOut")};");
        }

        sb.AppendLine("            delegate* unmanaged[Cdecl]<NativeApi.EngineChunkColumns*, float, void> fn = &RunChunk;");
        sb.AppendLine($"            fixed (byte* name = \"{systemName}\\0\"u8)");
        sb.AppendLine("            {");
        sb.AppendLine($"                return table->EngineSystemRegister(world, name, ids, access, {components.Count}u, fn, userData);");
        sb.AppendLine("            }");
        sb.AppendLine("        }");
        sb.AppendLine();
    }

    private static string SystemName(SystemSpec spec)
    {
        // Same spelling as Type.FullName minus nesting '+': "Ns.Outer.Inner".
        var parts = new List<string>();
        if (spec.Namespace.Length != 0)
        {
            parts.Add(spec.Namespace);
        }

        parts.AddRange(spec.ContainingTypes.Reverse().Select(static c => c.Name));
        parts.Add(spec.StructName);
        return string.Join(".", parts);
    }

    private static void EmitChunkRunner(StringBuilder sb, SystemSpec spec, TickSignatureSnapshot tick, string selfFqn)
    {
        var phases = tick.PhaseNames.Length != 0
            ? tick.PhaseNames
            : spec.StructPhaseNames;
        var phaseList = phases.Length != 0
            ? string.Join(", ", phases)
            : "Update";

        sb.AppendLine("        /// <summary>");
        sb.AppendLine($"        /// Zero-copy chunk runner (phases: {phaseList}).");
        sb.AppendLine("        /// Unpacks EngineChunkColumns into one span per component term and");
        sb.AppendLine("        /// invokes the user Tick per row with the frame delta.");
        sb.AppendLine("        /// </summary>");
        sb.AppendLine("        [UnmanagedCallersOnly(CallConvs = new[] { typeof(CallConvCdecl) })]");
        sb.AppendLine("        public static unsafe void RunChunk(NativeApi.EngineChunkColumns* view, float dt)");
        sb.AppendLine("        {");
        if (!IsRunnable(tick, selfFqn))
        {
            // Never bound (Register returned -2): keep the body inert.
            sb.AppendLine("            _ = view;");
            sb.AppendLine("            _ = dt;");
            sb.AppendLine("        }");
            return;
        }

        var components = ComponentParams(tick);
        sb.AppendLine("            int count = view->Count;");
        sb.AppendLine($"            if (count <= 0 || view->TermCount != {components.Count} || global::System.Threading.Volatile.Read(ref s_faulted) != 0)");
        sb.AppendLine("            {");
        sb.AppendLine("                return;");
        sb.AppendLine("            }");
        sb.AppendLine();
        for (var k = 0; k < components.Count; k++)
        {
            var p = components[k];
            var spanKind = p.RefKind == TickRefKind.In ? "ReadOnlySpan" : "Span";
            var elemType = k == 0 ? selfFqn : p.TypeName;
            sb.AppendLine($"            var col{k} = new {spanKind}<{elemType}>((void*)view->Columns[{k}], count);");
        }

        sb.AppendLine("            try");
        sb.AppendLine("            {");
        sb.AppendLine("                for (int i = 0; i < count; i++)");
        sb.AppendLine("                {");
        sb.AppendLine($"                    col0[i].Tick({string.Join(", ", RowArgs(tick))});");
        sb.AppendLine("                }");
        sb.AppendLine("            }");
        sb.AppendLine("            catch (global::System.Exception)");
        sb.AppendLine("            {");
        sb.AppendLine("                global::System.Threading.Volatile.Write(ref s_faulted, 1);");
        sb.AppendLine("            }");
        sb.AppendLine("        }");
    }

    // Component parameters in Tick order (scalars excluded). Index k is the
    // native term index and the column index col{k}.
    private static List<TickParameterSnapshot> ComponentParams(TickSignatureSnapshot tick)
    {
        var list = new List<TickParameterSnapshot>();
        foreach (var p in tick.Parameters)
        {
            if (!IsFloatScalar(p.TypeName))
            {
                list.Add(p);
            }
        }

        return list;
    }

    private static IEnumerable<string> RowArgs(TickSignatureSnapshot tick)
    {
        // Instance Tick is invoked through the column element itself
        // (col0[i].Tick(ref col0[i], ...)): the element is BOTH the receiver
        // AND the explicit ref/in self argument. C# does not fuse the hidden
        // `this` with an explicit `ref Self` parameter (CS7036 if omitted).
        var k = 0;
        foreach (var p in tick.Parameters)
        {
            if (IsFloatScalar(p.TypeName))
            {
                yield return p.RefKind == TickRefKind.In ? "in dt" : "dt";
                continue;
            }

            yield return (p.RefKind == TickRefKind.In ? "in col" : "ref col") + k.ToString(System.Globalization.CultureInfo.InvariantCulture) + "[i]";
            k++;
        }
    }

    private static bool IsRunnable(TickSignatureSnapshot tick, string selfFqn)
    {
        var components = new List<TickParameterSnapshot>();
        foreach (var p in tick.Parameters)
        {
            if (IsFloatScalar(p.TypeName))
            {
                // dt: by value or `in` only (a `ref float` would alias the
                // runner's parameter, which Tick must not write).
                if (p.RefKind == TickRefKind.Ref)
                {
                    return false;
                }

                continue;
            }

            if (p.RefKind == TickRefKind.None)
            {
                return false;
            }

            components.Add(p);
        }

        if (components.Count == 0 || components.Count > MaxTerms || components[0].TypeName != selfFqn)
        {
            return false;
        }

        return components.Select(static c => c.TypeName).Distinct(StringComparer.Ordinal).Count() == components.Count;
    }

    private static bool IsFloatScalar(string typeName)
    {
        return typeName == "float"
            || typeName == "global::System.Single"
            || typeName.EndsWith("::System.Single", StringComparison.Ordinal);
    }
