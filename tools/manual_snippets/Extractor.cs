// Program.cs — P7-06 extraction entry point (explicit Main: top-level
// statements cannot follow the Extractor type declaration).
using System.Text;
using System.Text.RegularExpressions;

internal static class Program
{
    internal static int Main(string[] args)
    {
        return Extractor.Run(args.Length > 0 ? args[0] : Directory.GetCurrentDirectory());
    }
}

internal static class Extractor
{
    internal static int Run(string repoRoot)
    {
        var manualDir = Path.Combine(repoRoot, "docs", "manual");
        var outDir = Path.Combine(repoRoot, "tools", "manual_snippets", "Generated");
        if (!Directory.Exists(manualDir))
        {
            Console.Error.WriteLine($"manual_snippets: no manual dir at {manualDir}");
            return 2;
        }

        Directory.CreateDirectory(outDir);
        foreach (var stale in Directory.GetFiles(outDir, "*.cs"))
        {
            File.Delete(stale);
        }

        var fence = new Regex("```csharp\\s*\\r?\\n(.*?)```", RegexOptions.Singleline);
        var sources = Directory.GetFiles(manualDir, "*.md").OrderBy(p => p, StringComparer.Ordinal);
        var total = 0;
        var failures = 0;
        foreach (var md in sources)
        {
            var text = File.ReadAllText(md);
            var name = Path.GetFileNameWithoutExtension(md).Replace("-", "_");
            var index = 0;
            foreach (Match m in fence.Matches(text))
            {
                var body = m.Groups[1].Value.Trim('\r', '\n');
                if (body.Length == 0)
                {
                    Console.Error.WriteLine($"manual_snippets: empty fence in {name} — every fence must hold one compilable member");
                    failures++;
                    continue;
                }

                var sb = new StringBuilder();
                sb.AppendLine("// <auto-generated> from docs/manual/" + Path.GetFileName(md) + $" fence {index}. DO NOT EDIT. </auto-generated>");
                sb.AppendLine("namespace ManualSnippets;");
                sb.AppendLine();
                sb.AppendLine($"internal unsafe partial class Snippets_{name}_{index}");
                sb.AppendLine("{");
                if (IsMember(body))
                {
                    sb.AppendLine(body);
                }
                else
                {
                    // Top-level statements: wrap in a method so the fence
                    // reads naturally in prose but still compiles.
                    sb.AppendLine("internal static void Run()");
                    sb.AppendLine("{");
                    sb.AppendLine(body);
                    sb.AppendLine("}");
                }

                sb.AppendLine("}");
                File.WriteAllText(Path.Combine(outDir, $"Snippets_{name}_{index}.cs"), sb.ToString());
                index++;
                total++;
            }
        }

        Console.WriteLine($"manual_snippets: {total} snippets from {manualDir} -> {outDir}");
        return failures == 0 && total > 0 ? 0 : 1;
    }

    // Heuristic: a fence is already a member when its first non-comment,
    // non-attribute line declares a type/member (or a using). Top-level
    // STATEMENTS (var x = ...; proc...; if (...) ...) get wrapped in
    // Run(). A bare local declaration that is really a member-less
    // fragment (no method/type keyword anywhere in the fence) is also a
    // statement. Fences that declare a method/type/using stay as-is.
    private static bool IsMember(string body)
    {
        // Attribute lines ([Foo]) precede members but never statements;
        // usings and access modifiers are always members.
        var member = new Regex(
            @"^\s*(using\s+(?!var\b|\()|\[|public\s|private\s|internal\s|protected\s|static\s|unsafe\s+[\w<>\[\]])",
            RegexOptions.Multiline);
        if (member.IsMatch(body))
        {
            return true;
        }

        // Arrow-bodied or block-bodied member: `<type> <Name>(...) =>` or
        // `<type> <Name>(...) {`. Statements never match this shape: a call
        // or `if`/`foreach` paren line never precedes `=>`/`{` on the SAME
        // line... except control-flow heads (`if (..) {`, `foreach (..) {`).
        // Those start with a keyword, so exclude them explicitly.
        var methodDecl = new Regex(
            @"^\s*(?!if\s|foreach\s|for\s|while\s|using\s|lock\s|fixed\s|switch\s|catch\s|checked\s|unchecked\s)[\w\[\]<>\.,\s]+\s+\w+\s*\([^;]*\)\s*(=>|\{)",
            RegexOptions.Multiline);
        if (methodDecl.IsMatch(body))
        {
            return true;
        }

        return false;
    }
}
